"""Data models for Ant Colony Optimization delivery representation."""
import math
from dataclasses import asdict, dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class ACOTaskNode:
    """Represents a location in the ACO decision graph: rider start, order pickup, or order dropoff."""
    node_id: str
    task_type: str  # "rider_start", "pickup", "dropoff"
    order_id: Optional[str] = None
    rider_id: Optional[str] = None
    lat: float = 0.0
    lon: float = 0.0
    ready_time_min: float = 0.0   # Earliest time task can be executed
    deadline_min: float = float("inf") # Latest desired time for completion
    service_time_min: float = 3.0 # Duration to collect or deliver order


@dataclass
class RiderTour:
    """Complete delivery sequence performed by a single rider."""
    rider_id: str
    capacity: int
    stops: List[ACOTaskNode] = field(default_factory=list)
    arrival_times: List[float] = field(default_factory=list)
    departure_times: List[float] = field(default_factory=list)
    loads: List[int] = field(default_factory=list)
    total_distance_km: float = 0.0
    total_time_min: float = 0.0
    orders_delivered: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "rider_id": self.rider_id,
            "capacity": self.capacity,
            "stops": [
                {
                    "node_id": s.node_id,
                    "task_type": s.task_type,
                    "order_id": s.order_id,
                    "lat": s.lat,
                    "lon": s.lon,
                    "ready_time_min": round(s.ready_time_min, 2) if not math.isinf(s.ready_time_min) else None,
                    "deadline_min": round(s.deadline_min, 2) if not math.isinf(s.deadline_min) else None,
                }
                for s in self.stops
            ],
            "arrival_times": [round(t, 2) for t in self.arrival_times],
            "departure_times": [round(t, 2) for t in self.departure_times],
            "loads": self.loads,
            "total_distance_km": round(self.total_distance_km, 3),
            "total_time_min": round(self.total_time_min, 2),
            "orders_delivered": self.orders_delivered,
        }


@dataclass
class DeliveryPlan:
    """Full candidate delivery plan across all riders generated by an ant."""
    tours: Dict[str, RiderTour] = field(default_factory=dict)
    total_distance_km: float = 0.0
    total_delivery_time_min: float = 0.0
    late_delivery_penalty: float = 0.0
    freshness_penalty: float = 0.0
    late_orders_count: int = 0
    unserved_orders_count: int = 0
    fitness_cost: float = float("inf")

    def to_dict(self) -> Dict[str, Any]:
        return {
            "total_distance_km": round(self.total_distance_km, 3),
            "total_delivery_time_min": round(self.total_delivery_time_min, 2),
            "late_delivery_penalty": round(self.late_delivery_penalty, 2),
            "freshness_penalty": round(self.freshness_penalty, 2),
            "late_orders_count": self.late_orders_count,
            "unserved_orders_count": self.unserved_orders_count,
            "fitness_cost": round(self.fitness_cost, 2) if not math.isinf(self.fitness_cost) else 999999.0,
            "tours": {r_id: tour.to_dict() for r_id, tour in self.tours.items()},
        }

    def summary(self) -> str:
        return (
            f"Fitness Cost: {self.fitness_cost:.2f} | Distance: {self.total_distance_km:.2f} km | "
            f"Travel Time: {self.total_delivery_time_min:.1f} min | Late Orders: {self.late_orders_count} | "
            f"Unserved: {self.unserved_orders_count}"
        )
